// Per-length pools, then a deterministic one-time shuffle of each, so picking
// by the level's index WITHIN its band yields UNIQUE words per band (no
// repeats, no gaps) while staying identical for every player.
export const WORDLE_POOLS = (() => {
    const pools = { 4: [], 5: [], 6: [] };
    WORDLE_PRACTICE.concat(WORD_EXTRA5, WORD_EXTRA6).forEach(p => {
        const n = [...p.word].length; if (pools[n]) pools[n].push(p);
    });
    const order = {};
    [4, 5, 6].forEach(len => {
        const a = pools[len].slice();
        let s = (len * 2654435761) >>> 0;
        for (let i = a.length - 1; i > 0; i--) { s = (s * 1664525 + 1013904223) >>> 0; const j = s % (i + 1);[a[i], a[j]] = [a[j], a[i]]; }
        order[len] = a;
    });
    return order;
})();

