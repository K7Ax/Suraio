export const CONNECTIONS_NUM_GROUPS = 4;   // always 4 solvable groups (16 words)
// Saudi groups guaranteed on every board. Two of four keeps the game's identity
// in front of the player on every single puzzle while letting the sixty-four
// general groups actually be played — see assembleConnections.
export const CONNECTIONS_SAUDI_PER_BOARD = 2;

// Assemble a board: 4 mutually-disjoint groups (Saudi-first) PLUS the band's
// decoy words. A pure function of (seed, numDecoys) — which is exactly what
// lets the bot pre-check the board a player will be handed weeks from now.
//
// `norm` is injected rather than imported for the same reason as in
// checks.mjs: core/util.js is .js+ESM and node cannot load it, and a second
// copy of normalizeArabic is the one duplication this repo has already been
// burned by (tests/normalize.test.js).
// `ordinal` is the campaign level (0..20) and is OPTIONAL: pass it to walk the
// pool systematically instead of sampling it, and omit it (daily, bot, practice)
// to keep the seed-only behaviour. See the «الدورات» note below.
export function assembleConnections(seed, numDecoys, norm, random, ordinal) {
    const rng = random ? Math.random : mulberry32(seed);
    // السلّم كان يسحب **بإرجاع**، فيعيد المجموعة نفسها.
    //
    // بذرةُ كل مستوًى مستقلّة، فاختيار مجموعتين سعوديّتين من عشرين في كلّ لوحٍ
    // سحبٌ بإرجاعٍ لا مسحٌ للبنك: قِيس على السلّم كلّه ثلاثةُ تجاورٍ تتشارك فيها
    // مرحلتان متتاليتان مجموعةً أو مجموعتين — ٨/٩ تتشاركان «مدن» و«جواهر» معًا،
    // أي نصف اللوح — وأربع مرّاتٍ لأشدّ المجموعات تكرارًا. وهذا هو النصف الثاني
    // من بلاغ المالك: «حتى نفس الكلمات».
    //
    // العلاج: حين يُمرَّر ترتيب المستوى، تُقرأ القائمة **دورةً كاملة** — كلّ
    // دورةٍ ترتيبٌ جديد، والمستوى يأخذ شريحته منها بلا إرجاع. عشرون مجموعةً
    // سعوديّة واثنتان لكل لوح: عشرة مستوياتٍ تستوعب البنك السعوديّ كلّه مرّةً
    // واحدة بلا أيّ تكرار، ثمّ تبدأ دورةٌ بترتيبٍ مختلف فلا يتكرّر الاقتران.
    // وأربعٌ وستّون عامّةً واثنتان لكل لوح: دورةٌ واحدة تغطّي السلّم كلّه، فصفرُ
    // تكرارٍ في المجموعات العامّة على المستويات الواحد والعشرين.
    //
    // البذرة تبقى هي هي وقتَ غياب `ordinal`، فمسار «تحدي اليوم» ومسار البوت
    // اللذان يستدعيان الدالّة ببذرةٍ وحدها لم يتغيّر لهما لوحٌ واحد.
    const slice = (list, per) => {
        if (random || ordinal == null || !list.length) return seededShuffle(list, rng);
        const cycle = Math.floor((ordinal * per) / list.length);
        const at = (ordinal * per) % list.length;
        // ترتيبٌ ثابتٌ لكلّ دورة — مستقلٌّ عن بذرة المستوى عمدًا، وإلا عاد
        // السحب بإرجاع من حيث طُرد.
        const ring = seededShuffle(list, mulberry32(0x5EED + cycle * 7919));
        return ring.slice(at).concat(ring.slice(0, at));
    };
    const order = [
        ...slice(CONNECTIONS_POOL.filter(g => g.saudi), CONNECTIONS_SAUDI_PER_BOARD),
        ...slice(CONNECTIONS_POOL.filter(g => !g.saudi),
            CONNECTIONS_NUM_GROUPS - CONNECTIONS_SAUDI_PER_BOARD)
    ];
    // SAUDI-FIRST WAS SAUDI-ONLY, AND SILENTLY.
    //
    // Concatenating the two shuffles and taking the first four disjoint groups
    // means the four always came out of the twenty Saudi entries — four disjoint
    // groups are always available that early, so the loop never reached the
    // sixty-four general ones. The pool reads as 84 groups and behaved as 20:
    // «تشابك» repeated because its real bank was a quarter of its apparent size,
    // and the other sixty-four could only ever appear as decoys.
    //
    // The quota makes the intent explicit instead of leaving it to an accident
    // of ordering: two Saudi groups on every board — the identity is visible in
    // every single puzzle, which the old code did not actually guarantee either
    // — and two from the general pool. `take` runs the general pass over the
    // whole ordering as a fallback, so a board is still assembled even if the
    // general pool were ever too small or too entangled.
    const chosen = [], usedWords = new Set();
    const take = (list, count) => {
        for (const g of list) {
            if (count <= 0) break;
            if (chosen.includes(g)) continue;
            const n = g.words.map(norm);
            if (n.some(w => usedWords.has(w))) continue;
            n.forEach(w => usedWords.add(w));
            chosen.push(g);
            count--;
        }
        return count;
    };
    const saudi = order.filter(g => g.saudi), general = order.filter(g => !g.saudi);
    const missing = take(saudi, CONNECTIONS_SAUDI_PER_BOARD);
    // Any Saudi shortfall is handed to the general pass rather than dropped, so
    // the board is always four groups.
    take(general, CONNECTIONS_NUM_GROUPS - CONNECTIONS_SAUDI_PER_BOARD + missing);
    if (chosen.length < CONNECTIONS_NUM_GROUPS) take(order, CONNECTIONS_NUM_GROUPS - chosen.length);
    // decoys: one word each from distinct groups that share NOTHING with the
    // board, so a decoy can never accidentally form a group — it only misleads.
    //
    // «Shares nothing» has to be checked against the group, not just the word.
    // Nineteen words in the pool sit in two groups («كليجا» in both حلويات شعبية
    // and حلويات شرقية), so a decoy drawn from حلويات شرقية while حلويات شعبية is
    // on the board hands the player a fifth word that genuinely belongs to a
    // board group — ambiguity, not misdirection. This used to hold by accident:
    // the decoy scan resumed after the four chosen groups, so it stepped over the
    // entangled neighbours that happened to sit earlier in the ordering. Once the
    // Saudi quota changed where the scan begins, the accident stopped holding.
    // AND THE DECOYS HAD A VOCABULARY OF EIGHTEEN WORDS.
    //
    // بلاغ المالك (١٢ أغسطس ٢٠٢٦): «نفس الألغاز في كل الألعاب، بس قاعد تتغير
    // طريقة الحل، حتى نفس الكلمات». وهو محقّ: المجموعات الأربع كانت تتبدّل فعلًا،
    // لكن نصف اللوح في المستويات الصعبة تمويهٌ، وكان التمويه يعيد الكلمات نفسها
    // في كل مستوًى — طويق، لؤلؤ، الرياض، كبسة، الزل، السدو، الهجن، المها…
    //
    // سببان متراكبان، كلاهما هنا:
    //   ١. المسح كان يجري على `order` وهي «سعوديّةٌ أوّلًا ثم عامّة». وبما أن
    //      اللوح يأخذ مجموعتين سعوديّتين فقط من نحو عشرين، تبقى ثماني عشرة
    //      مجموعةً سعوديّةً قبل أوّل مجموعةٍ عامّة — فلا يبلغ المسحُ الأربعَ
    //      والستّين العامّة أبدًا. بنك التمويه المعلَن ٨٤ وسلوكه ١٨.
    //   ٢. `find` تأخذ **أوّل** كلمةٍ غير مستعملة في المجموعة، فتُسهم كل مجموعةٍ
    //      بالكلمة نفسها في كل مرّة.
    //
    // العلاج: خلطةٌ مستقلّة للتمويه على البنك **كلّه** (لا ترتيب اللوح)، واختيار
    // كلمةٍ بالقرعة من داخل المجموعة لا أوّلها. وكلاهما مبذورٌ من `rng` نفسه،
    // فاللوح يبقى حتميًّا لكل مستوًى كما كان.
    const boardWords = new Set(chosen.flatMap(g => g.words.map(norm)));
    const decoyWords = [];
    const pool = seededShuffle(order.filter(g => !chosen.includes(g)), rng);
    for (const g of pool) {
        if (decoyWords.length >= numDecoys) break;
        if (g.words.some(x => boardWords.has(norm(x)))) continue;
        const free = g.words.filter(x => !usedWords.has(norm(x)));
        if (!free.length) continue;
        const w = free[Math.floor(rng() * free.length) % free.length];
        usedWords.add(norm(w));
        decoyWords.push(w);
    }
    return { groups: chosen, decoys: decoyWords };
}
