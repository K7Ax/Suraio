// scripts/assets/hero_layers.js — يبني طبقات الهيرو من اللوحة الأصلية.
//
//   node scripts/assets/hero_layers.js
//
// المدخل : _design-src/story/Man_standing_up_dessert.png  (لوحة المالك، 1672×941)
// المخرج : public/hero/{sky,near}-{1280,2560}.webp  +  hero-flat-{1280,2560}.webp
//
// ---------------------------------------------------------------------------
// لماذا طبقتان فقط، والخطة كانت أربعًا؟
//
// العمق المحسوس في الـparallax ليس عدد الطبقات، بل **الفرق** بين معاملات
// عمقها. وقياس الفروق على هذه اللوحة تحديدًا حسم الأمر:
//
//   القمر  d=0.06 مقابل السماء d=0.03  →  فرق 0.03  →  3px عند 2560
//   البلدة d=0.10 مقابل السماء d=0.03  →  فرق 0.07  →  7px
//   الكثيب d=0.65 مقابل السماء d=0.03  →  فرق 0.62  →  64px   ← العمق كلّه هنا
//
// ثلاثة بكسلات لا تُرى. فقصُّ القمر والبلدة كان سيشتري صفرًا من العمق بثمن
// ثقبين إضافيين يجب ترميمهما، وحافّتين إضافيتين قد تُظهران هالة. حُذفتا.
//
// وقصُّ القمر كان سيكسر شيئًا أسوأ: هالته الضوئية تمتدّ عشرات البكسلات في
// السماء. قصٌّ ضيّق حول القرص يترك الهالة في طبقة السماء، فتنزلق الهالة بعيدًا
// عن قمرها عند أول حركة — وهذا عطل يُرى فورًا.
//
// طبقتان بفرق عمق كبير تقرآن أعمق من خمس طبقات بفروق مجهرية وحوافّ مشبوهة.
// ---------------------------------------------------------------------------
const sharp = require('sharp');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const SRC = path.join(ROOT, '_design-src', 'story', 'Man_standing_up_dessert.png');
const WORK = path.join(ROOT, '.hero_work');
const OUT = path.join(ROOT, 'public', 'hero');

// الهدف 2560 عرضًا: شاشة 1440 CSS-px على كثافة 2x تحتاج 2880 بكسلًا فيزيائيًّا،
// والأصل 1672 وحده كان سيُمدّ 1.7× — وهي بالضبط شكوى «الدقّة منخفضة» التي
// بدأت منها هذه الجولة.
const W = 2560, H = 1440;

// كم بكسلًا يجب أن يوجد من «سماء» تحت خطّ الحرف؟
// أقصى إزاحة نسبية بين الطبقتين = فرق العمق (0.62) × مدى الـparallax (4%)
// = 2.5% من العرض ≈ 64px، يُضاف إليها إزاحة الدخول الرأسية (~26px). و120
// هامشٌ مريح فوق ذلك، ولا يكلّف شيئًا لأن المنطقة تحت الحرف مخفيّة دائمًا.
const FILL = 120;

// ألفا أقلّ من هذا تُعتبر خارج الطبقة عند البحث عن خطّ الحرف. لا علاقة له
// بحدّة الحافّة نفسها — تلك تبقى بتدرّجها الأصلي من القناع.
const EDGE = 128;

async function gray(file) {
    const { data, info } = await sharp(file)
        .resize(W, H, { kernel: 'lanczos3', fit: 'fill' })
        .greyscale().raw().toBuffer({ resolveWithObject: true });
    if (info.channels !== 1) throw new Error(`${file}: expected 1 channel, got ${info.channels}`);
    return data;
}

(async () => {
    if (!fs.existsSync(SRC)) throw new Error(`missing plate: ${SRC}`);
    fs.mkdirSync(OUT, { recursive: true });

    // اللوحة مرفوعة إلى مقاس العرض. lanczos3 لا يخترع تفصيلًا، لكنه أفضل ما
    // يمكن فعله بلا توليد — والمشهد ضبابي متدرّج أصلًا، أي أقلّ ما يتأثّر بالرفع.
    const plate = await sharp(SRC)
        .resize(W, H, { kernel: 'lanczos3', fit: 'fill' })
        .removeAlpha().raw().toBuffer();

    // قناع الطبقة الأمامية = الكثيب ∪ المسافر.
    // اتّحادٌ لا طبقتين: هو **واقف على** الكثيب، فلو تحرّك بعمق مختلف عن أرضه
    // لانفصل عنها وطفا فوقها — عطلٌ يُرى في الثانية الأولى.
    const mNear = await gray(path.join(WORK, 'mask_near.png'));
    const mMan = await gray(path.join(WORK, 'mask_man.png'));
    const A = Buffer.alloc(W * H);
    for (let i = 0; i < A.length; i++) A[i] = Math.max(mNear[i], mMan[i]);

    // ---- الطبقة الأمامية: نفس البكسلات، وألفا من القناع -------------------
    const nearRGBA = Buffer.alloc(W * H * 4);
    for (let i = 0, p = 0, q = 0; i < W * H; i++, p += 3, q += 4) {
        nearRGBA[q] = plate[p]; nearRGBA[q + 1] = plate[p + 1];
        nearRGBA[q + 2] = plate[p + 2]; nearRGBA[q + 3] = A[i];
    }

    // ---- السماء: اللوحة كاملةً، وقد رُمّم ما كان تحت الكثيب ---------------
    // الترميم من **أقرب بكسل سليم في ثلاثة اتجاهات** (أعلى · يسار · يمين)
    // موزونًا بمقلوب المسافة.
    //
    // المحاولة الأولى كانت امتدادًا مرآتيًّا رأسيًّا، وفشلت فشلًا مرئيًّا:
    // ما فوق حرف الكثيب منحدرٌ مضاء، فسحبُه إلى أسفل صنع شريطًا فاتحًا عريضًا
    // مكان ظلّ الكثيب — وأسوأ منه عمودٌ شاحب كامل تحت المسافر، لأن ما فوق رأسه
    // سماء، فامتدّت السماء إلى الأرض.
    //
    // والاتجاه الأفقي هو الصحيح في هذا المشهد تحديدًا: نطاقات الكثبان تجري
    // أفقيًّا، فالبكسل السليم على **نفس الارتفاع** يمينًا أو يسارًا يحمل نفس
    // الإضاءة تقريبًا. ووزن المسافة يجعله يغلب تلقائيًّا حيث يكون قريبًا
    // (عَرض المسافر ~50px) ويترك الأعلى يقود حيث يتّسع القناع.
    const sky = Buffer.from(plate);
    const patched = new Uint8Array(W * H);   // أين رمّمنا — لحصر التمويه

    // ترميمٌ **انتشاري**: تمويهٌ متكرّر بنصف قطر متناقص، ويُعاد في كل شوط ما هو
    // خارج المنطقة إلى قيمته الأصلية. فتزحف قيم الحافّة إلى الداخل بتدرّج
    // ناعم، وهو ما يُرى كامتداد طبيعي للكثبان.
    //
    // المحاولة الثانية كانت «أقرب بكسل سليم موزونًا بمقلوب المسافة»، وفشلت
    // لسببٍ رياضي لا فنّي: البكسل الملاصق فوق رأس المسافر مسافتُه ١، فوزنُه
    // يطغى على الجيران الأفقيين (مسافة ~٢٥) بخمسةٍ وعشرين ضعفًا — فيُنسَخ
    // بكسلٌ واحد على طول العمود، ويظهر لوحًا مصمتًا شاحبًا. الانتشار لا يعرف
    // هذا العيب: لا مصدر واحد يفوز، بل الحدّ كلّه يساهم بحسب قربه فعلًا.
    //
    // `band` يحصر العمل في شريط ملاصق لحافّة القناع العليا (0 = بلا حصر): ما
    // هو أعمق لا يُكشف أبدًا مهما تحرّكت الطبقة، فترميمه إنفاقٌ بلا رؤية.
    //
    // ونصف القطر يجب أن يناسب **عَرض** المنطقة، لا أن يكون واحدًا للاثنتين:
    // المسافر عرضه ~٥٠px، فنصف قطر ٦٤ يتجاوزه إلى شريط الأفق المضيء تحته
    // ويسحبه إلى أعلى فوق جذعه — وهذا هو العمود الشاحب الذي بقي بعد إصلاح
    // الكثيب. أمّا شريط الكثيب فيمتدّ ١٢٠px رأسيًّا ويحتاج المدى الواسع فعلًا.
    async function inpaint(target, band, radii) {
        const fill = new Uint8Array(W * H);
        let cols = 0;
        for (let x = 0; x < W; x++) {
            let top = -1;
            for (let y = 0; y < H; y++) { if (target[y * W + x] >= EDGE) { top = y; break; } }
            if (top < 0) continue;
            cols++;
            const end = band ? Math.min(H, top + band) : H;
            for (let y = top; y < end; y++) {
                const i = y * W + x;
                if (target[i] >= EDGE) { fill[i] = 1; patched[i] = 1; }
            }
        }
        // من الواسع إلى الضيّق: الأشواط الأولى تنقل الإضاءة العامة عبر المنطقة
        // كلّها، والأخيرة تُحكم الالتحام عند الحافّة نفسها.
        for (const r of radii) {
            const blur = await sharp(sky, { raw: { width: W, height: H, channels: 3 } })
                .blur(r).raw().toBuffer();
            for (let i = 0, p = 0; i < W * H; i++, p += 3) {
                if (!fill[i]) continue;
                sky[p] = blur[p]; sky[p + 1] = blur[p + 1]; sky[p + 2] = blur[p + 2];
            }
        }
        return cols;
    }

    // شوطان، والترتيب هو الفرق بين مشهدٍ سليم وشبحٍ مرئي.
    //
    // ١) المسافر أولًا، والكثيب حينها مصدرٌ **سليم** له. فما فوق رأسه سماء
    //    وما تحت قدميه ظلّ الكثيب، ويُملأ كلٌّ من جهته الصحيحة.
    //    الشوط الأول بلا حصر شريط: قامته كلّها تُملأ.
    // ٢) ثم الكثيب، وقد اختفى المسافر من مصادره.
    //
    // بالترتيب المعكوس (أو بشوط واحد على الاتّحاد) يصير أقربُ مصدرٍ لأعلى عمود
    // المسافر هو السماء وحدها، فتمتدّ السماء إلى ما تحت خطّ الحرف — وهذا هو
    // بالضبط العمود الشاحب الذي ظهر في أول تركيب.
    // ١) المسافر: **نسخ رقعة أفقية**، لا انتشار.
    //
    // الانتشار يصنع لطخةً ناعمة لا نسيجًا، وطيفٌ ناعم بشكل إنسان يبقى مقروءًا
    // مهما خفّ — وهذه المنطقة تُرى فعلًا: المسافر يسافر مع الطبقة الأمامية،
    // فموضعه القديم في السماء ينكشف كاملًا عند أقصى إزاحة (64px).
    //
    // ونطاقات الكثبان على ارتفاعه تجري **أفقيًّا**، فالبقعة على بُعد 170px
    // يمينًا تحمل نفس الإضاءة ونفس النسيج ولا مسافرَ فيها. النسخ منها يعطي
    // امتدادًا حقيقيًّا للمشهد بدل تمويهٍ يشي بنفسه.
    //
    // والمزج بألفا القناع نفسه: حافّته مُنعَّمة أصلًا، فتذوب الرقعة فيما حولها
    // بلا خطّ.
    // ومع النسخ **تصحيحُ سطوعٍ سطرًا بسطر**، وهو ما يجعل الرقعة تختفي فعلًا.
    // خطّ الأفق في هذه اللوحة مائل، فالنسخ الأفقي وحده ينقل الكثبانَ المضيئة
    // إلى ارتفاع رأس المسافر حيث يجب أن تكون سماءً أغمق — وهذا هو الطيف الذي
    // بقي مرئيًّا بعد النسخ المجرّد. القياس على المتوسّط العام لا يكشفه لأن
    // الرأس يفتح والقدمين تُظلم فيتعادلان في الرقم.
    //
    // فلكل سطر: يُؤخذ متوسّط الجارين السليمين يمينًا ويسارًا في **ذلك السطر**،
    // ويُزاح متوسّط الرقعة إليه. النسيج من الرقعة، والمستوى من المحيط.
    // القناع مُوسَّعٌ قليلًا قبل النسخ. حافّة القناع مُنعَّمة (ألفا جزئية)،
    // وعندها يُمزج الترميم مع بكسلات المسافر الداكنة نفسها فيبقى **خيطٌ** رفيع
    // يرسم محيطه. التوسيع يبتلع ذلك الشريط الانتقالي كلّه، ولا يكلّف شيئًا:
    // ما يُستبدل زيادةً هو سماءٌ تُستبدل بسماء مطابقة المستوى.
    //
    // `toColourspace('b-w')` ليس زخرفة: sharp يُخرج **ثلاث** قنوات من مُدخَل
    // رمادي خام ما لم يُطلب غير ذلك، فيصير الفهرس يقرأ من مخزن RGB متداخل —
    // وقد أنتج ذلك صفرَ بكسل موسَّع، أي أن المسافر عاد كاملًا إلى طبقة السماء
    // بلا أي خطأ ظاهر في السجلّ.
    const mManD = await sharp(Buffer.from(mMan), { raw: { width: W, height: H, channels: 1 } })
        .blur(3).toColourspace('b-w').raw().toBuffer({ resolveWithObject: true });
    if (mManD.info.channels !== 1) throw new Error(`dilate returned ${mManD.info.channels} channels`);
    for (let i = 0; i < mMan.length; i++) mMan[i] = Math.min(255, mManD.data[i] * 3);

    const DX = 170, RING = 24;
    for (let y = 0; y < H; y++) {
        let lo = -1, hi = -1;
        for (let x = 0; x < W; x++) { if (mMan[y * W + x] >= 32) { if (lo < 0) lo = x; hi = x; } }
        if (lo < 0) continue;
        const mean = (x0, x1) => {
            const a = [0, 0, 0]; let n = 0;
            for (let x = Math.max(0, x0); x <= Math.min(W - 1, x1); x++) {
                const i = y * W + x;
                if (mMan[i] >= 32) continue;              // الجار يجب أن يكون سليمًا
                const p = i * 3; a[0] += plate[p]; a[1] += plate[p + 1]; a[2] += plate[p + 2]; n++;
            }
            return n ? [a[0] / n, a[1] / n, a[2] / n, n] : null;
        };
        const L = mean(lo - RING, lo - 1), R = mean(hi + 1, hi + RING);
        const ref = L && R ? [0, 1, 2].map(c => (L[c] + R[c]) / 2) : (L || R);
        if (!ref) continue;
        // متوسّط الرقعة في هذا السطر
        const s = [0, 0, 0]; let sn = 0;
        for (let x = lo; x <= hi; x++) {
            if (mMan[y * W + x] < 32) continue;
            const p = (y * W + Math.min(W - 1, x + DX)) * 3;
            s[0] += plate[p]; s[1] += plate[p + 1]; s[2] += plate[p + 2]; sn++;
        }
        if (!sn) continue;
        const shift = [0, 1, 2].map(c => ref[c] - s[c] / sn);
        for (let x = lo; x <= hi; x++) {
            const i = y * W + x;
            const a = mMan[i] / 255;
            if (a < 0.004) continue;
            const sp = (y * W + Math.min(W - 1, x + DX)) * 3, dp = i * 3;
            for (let c = 0; c < 3; c++) {
                const v = Math.max(0, Math.min(255, plate[sp + c] + shift[c]));
                sky[dp + c] = a * v + (1 - a) * sky[dp + c];
            }
            patched[i] = 1;
        }
    }
    // ٢) ثم شريط الكثيب، بالانتشار — وهو يليق به: ما يُكشف منه ضبابٌ وكثبان
    //    متدرّجة بلا تفصيل حادّ، أي أن اللطخة الناعمة هي الشكل الصحيح هنا.
    const cols = await inpaint(mNear, FILL, [64, 32, 16, 8, 4, 2]);
    if (!cols) throw new Error('mask covered no column — masks and plate are misaligned');

    // لا تمويه إضافي هنا: الانتشار ينتهي بنصف قطر ٢، وأي تمويه بعده يعيد
    // تلطيخ ما أُحكِم للتوّ عند الحافّة.

    // ---- التصدير ----------------------------------------------------------
    // السماء بلا ألفا: هي القاعدة، ولا شيء خلفها. الأمامية بألفا.
    // مقاسان: 2560 للشاشات الكثيفة و1280 لما دونها، يختار بينهما `srcset`.
    const jobs = [];
    for (const w of [2560, 1280]) {
        jobs.push(sharp(sky, { raw: { width: W, height: H, channels: 3 } })
            .resize(w, Math.round(w * H / W), { kernel: 'lanczos3' })
            .webp({ quality: w === 2560 ? 72 : 76, effort: 6 })
            .toFile(path.join(OUT, `sky-${w}.webp`)));

        jobs.push(sharp(nearRGBA, { raw: { width: W, height: H, channels: 4 } })
            .resize(w, Math.round(w * H / W), { kernel: 'lanczos3' })
            .webp({ quality: w === 2560 ? 82 : 84, alphaQuality: 100, effort: 6 })
            .toFile(path.join(OUT, `near-${w}.webp`)));

        // المسار الضعيف: اللوحة مسطّحةً، صورةٌ واحدة تُحرَّك بـgsapDrift.
        jobs.push(sharp(plate, { raw: { width: W, height: H, channels: 3 } })
            .resize(w, Math.round(w * H / W), { kernel: 'lanczos3' })
            .webp({ quality: w === 2560 ? 70 : 72, effort: 6 })
            .toFile(path.join(OUT, `flat-${w}.webp`)));
    }
    const done = await Promise.all(jobs);

    console.log(`plate ${W}x${H} · patched ${cols} columns · fill ${FILL}px`);
    for (const r of done) console.log(`  ${r.format} ${r.width}x${r.height} ${(r.size / 1024).toFixed(0)}KB`);
    const total = done.filter(r => r.width === 2560).reduce((n, r) => n + r.size, 0);
    console.log(`hero @2560 (sky+near) = ${((done[0].size + done[1].size) / 1024).toFixed(0)}KB`);
})();
