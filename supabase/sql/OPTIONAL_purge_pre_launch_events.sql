-- ============================================================
--
-- **ما في القاعدة الآن ليس زوّارًا.** الموقعُ لم يُنشر، و`game_events` تحمل:
--   • تشغيلاتِ اختبارِ الحمل (`scripts/qa/loadtest.js`)،
--   • مسوحَ المتصفّح الآليّة (كلُّ سياقٍ جديدٍ = معرِّفُ جهازٍ جديد)،
--   • جلساتِ الفحص اليدويّ.
--
-- والقياس: 85.1٪ من المعرِّفات (998 من 1,173) سجّلت **حدثًا واحدًا فقط**،
-- و1,215 حدثَ `site_visit` موزّعةً على 1,162 معرِّفًا.
--
-- وهجرةُ `20260815_02` تصحّح **معنى** الكلمة (لاعب = بدأ مستوًى)، وهي وحدَها
-- كافيةٌ لئلّا تُخدَع بالرقم. أمّا هذا الملفّ فيعالج شيئًا آخر: أن يبقى تاريخُ
-- ما قبل الإطلاق مختلطًا بما بعده إلى الأبد، فلا يُقاس أثرُ الإطلاق أصلًا.
--
-- **البديلُ الأسلم:** لا تحذف شيئًا، واقرأ التقاريرَ بالشهر — سبتمبر وحدَه
-- سيكون نظيفًا. اختر الحذف فقط إن أردتَ لوحًا فارغًا تمامًا.


-- ── ١) اعرف أوّلًا. لا تحذف قبل أن ترى ما ستحذفه ──────────────────────
select count(*)                       as events,
       count(distinct device_id)      as devices,
       min(created_at)                as first,
       max(created_at)                as last
from public.game_events;

-- وما ستُبقيه — الحساباتُ الحقيقيّةُ إن وُجدت:
select count(*) as events_from_signed_in_users
from public.game_events where user_id is not null;


-- ── ٢) الحذف. سطرٌ واحد، وبعده لا رجعة ────────────────────────────────
-- شغّله **داخل معاملة** واقرأ العدد قبل أن تُثبّت:
--
--   begin;
--   delete from public.game_events where user_id is null;
--   -- انظر عدد الصفوف المحذوفة. إن بدا صحيحًا:
--   commit;      -- أو:  rollback;  إن لم يبدُ
--
-- ‏`user_id is null` شرطٌ مقصود: يُبقي كلَّ حدثٍ ارتبط بحسابٍ حقيقيّ — وهي
-- جلساتُك أنت — ويحذف المجهولَ وحدَه. وإن أردتَ الأرضَ خاليةً تمامًا فاحذف
-- الشرط، وستفقد معه تاريخَ حسابك.
--
-- ولا تُمَسّ `feedback_reports` ولا `feedback_ratings` هنا: البلاغاتُ الخمسة
-- الحاليّة نصوصُ تجربةٍ («اهلا وسهلا ممتاز») وتُغلَق من /inbox بزرّ الحالة —
-- وهو أنظفُ من حذفِ صفوفٍ من جدولٍ له تدقيق.


