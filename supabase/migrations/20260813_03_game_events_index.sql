-- فهرسٌ مركّب لـ`game_events`  (نتيجة التدقيق F11)
--
-- `my_stats()` تمرّ على صفوف المستخدم ثلاث مرّات في كلّ تحميلٍ للصفحة: مرّةً
-- لأيّام السلسلة، ومرّةً للبدايات، ومرّةً للإتمامات — وكلٌّ منها تُرشّح
-- `event_type`. والفهرس الوحيد المطابق هو `game_events_user_idx (user_id)`،
-- عمودٌ واحد. فكلّ مرّةٍ تقرأ **كلّ** صفوف المستخدم ثمّ ترشّح في الكومة.
--
-- وهذا مجّانيٌّ اليوم — ٣٬٩٠٠ صفٍّ لكلّ المستخدمين — والتقرير قال ذلك صراحةً
-- ولم يزعم غيره. إنّما هو مجّانيٌّ **اليوم**: عند ألف حدثٍ للاعبٍ نشط تصير
-- ثلاث قراءاتٍ كاملةٍ في كلّ فتحةِ صفحة. والفهرس يُضاف قبل أن يلزم، لأنّ
-- إضافته بعد أن يلزم تكون تحت ضغط.
--
-- و`concurrently` كي لا يُقفَل الجدول أثناء البناء — **ولذلك لا يجوز أن يكون
-- داخل معاملة**: يُلصَق هذا السطر وحده في محرّر SQL، لا ضمن كتلةٍ أكبر.
--
-- ترتيب الأعمدة مقصود: `user_id` يساوي، ثمّ `event_type` يساوي (أو `in`)،
-- ثمّ `created_at` مدًى وترتيبًا — وهو نفس شكل الاستعلامات الثلاثة بعد
-- ترحيل `20260813_02` الذي أدخل أحداث «تحدي اليوم» في العدّ.

create index concurrently if not exists game_events_user_type_time_idx
  on public.game_events (user_id, event_type, created_at);
