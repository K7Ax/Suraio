// ‏حرّاسُ الدخول والتسجيل.
//
// ‏كُتب هذا الملفّ لأنّ المسحَ عند إخراج `initAuth` من `src/main.js` أظهر أنّ
// ‏أخطرَ كتلةٍ في المشروع — ثمانمئةَ سطرٍ تملك الحساباتِ كلَّها — لم يكن عليها
// ‏حارسٌ واحدٌ في `tests/`. انحدارُها الصامت لا يُفسد رسمًا يُرى، بل يقفل بابًا
// ‏على لاعبٍ لن يبلّغ عنه: سيظنّ أنّه نسي كلمتَه.
//
// ‏وما يُقاس هنا مصدرٌ لا سلوكٌ حيّ — السلوكُ تقيسه بصمةُ `scripts/qa/fingerprint.js`
// ‏(مجسُّ `auth`). الاثنان يكمّلان بعضهما: البصمةُ تحرس النقلةَ، وهذه تحرس المعنى.
const test = require("node:test");
const assert = require("node:assert");
const fs = require("node:fs");
const path = require("node:path");
const { ROOT, read, assertWired } = require("./helpers/ui.js");

const AUTH = read("auth");

test("وحدة الدخول مستورَدةٌ ومُناداة", () => {
    assertWired(assert, "initAuth", "ui/auth\\.js");
});

// ‏العميلُ يرفض اسمًا سيرفضه الخادم على أيّ حال، لكنّ الرفضَين يجب أن يكونا
// ‏النمطَ نفسَه حرفًا بحرف. لو تراخى العميلُ وحده لرأى اللاعبُ «تمّ» ثمّ خطأً
// ‏غامضًا من الخادم؛ ولو تشدّد وحده لمُنع اسمٌ مقبول. النمطُ يعيش في مكانين
// ‏بحكم الحدود — فالحارسُ يقرأ الاثنين ويقارنهما، لا يعيد كتابةَ أحدهما.
test("نمط اسم المستخدم في العميل هو نفسه الذي يفرضه الخادم", () => {
    const SQL = fs.readFileSync(
        path.join(ROOT, "supabase", "sql", "db-security-definer.sql"), "utf8");
    const client = AUTH.match(/const USERNAME_RE = \/(.+?)\/;/);
    assert.ok(client, "USERNAME_RE اختفى من وحدة الدخول");
    const server = SQL.match(/!~ '(\^\[a-z0-9_\].+?)'/);
    assert.ok(server, "set_username لم يعد يفرض نمطًا — أو تغيّرت صياغته");
    assert.equal(client[1], server[1],
        `العميل يفرض ${client[1]} والخادم يفرض ${server[1]}`);
});

// ‏الحدُّ الأدنى قرارُ مالكٍ (ثمانية) ويعيش في ثابتٍ واحد. تسجيلُ الدخول يفحص
// ‏الطولَ برقمٍ حرفيٍّ عمدًا ولا يُقاس هنا: حساباتٌ أُنشئت قبل رفع الحدّ ما
// ‏زالت صالحة، فربطُه بـ`MIN_PW` كان سيقفل عليها البابَ عند أيّ رفعٍ لاحق.
test("كلُّ مسارات الإنشاء تمرّ بمقياسٍ واحدٍ للقوّة", () => {
    assert.match(AUTH, /const MIN_PW = 8;/, "MIN_PW لم يعد ثمانية أو تفكّك");
    assert.match(AUTH, /pw\.length >= MIN_PW/, "isStrongPassword لا يقرأ MIN_PW");
    // ‏المعالجُ ولوحُ كلمة المرور الجديدة: كلاهما يستدعي الدالّة لا يعيد الفحص.
    const calls = (AUTH.match(/!isStrongPassword\(/g) || []).length;
    assert.ok(calls >= 2, `مسارُ إنشاءٍ يفحص القوّةَ بنفسه: ${calls} استدعاءً فقط`);
});

// ‏الانحدارُ الذي وقع فعلًا مرّةً: العائدُ من Google كان يُدفع إلى لوح «عيّن
// ‏كلمةَ مرورٍ جديدة» لأنّ الوحدةَ فتحته لمجرّد وجود جلسةٍ في الـhash. اللوحُ
// ‏لا يُفتح إلّا لرابط استعادةٍ صريح.
test("لوح كلمة المرور الجديدة لا يُفتح إلّا على type=recovery", () => {
    assert.match(AUTH, /hp\.get\('type'\) === 'recovery'/,
        "شرطُ الاستعادة الصريح اختفى — عائدو Google سيُدفعون إلى لوح كلمة مرور");
    assert.match(AUTH, /recoveryHandled/,
        "حارسُ المرّة الواحدة اختفى: الاستعادة قد تُعالَج مرّتين");
});

// ‏لا شيءَ من هذا يُطبع ولا يُرسل. الفحصُ نصّيٌّ غليظٌ عمدًا: قيمةُ حقلِ كلمةِ
// ‏مرورٍ لا ينبغي أن تقترب من `console` ولا من قناة القياس أصلًا.
test("لا كلمةَ مرورٍ تُطبع ولا تُقاس", () => {
    const bad = AUTH.split("\n")
        .map((l, i) => [i + 1, l])
        .filter(([, l]) => /(console\.\w+|track)\(/.test(l) && /password|\bpw\b/i.test(l));
    assert.deepEqual(bad, [], `سطورٌ تمرّر كلمةَ مرورٍ إلى الطباعة أو القياس: ${JSON.stringify(bad)}`);
});
